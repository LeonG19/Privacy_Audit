"""Turn one or more `ci_audit vary` run directories into a review sheet (CSV + side-by-side Markdown) and print a readiness summary.

    python scripts/variation_review_sheet.py data/processed/variations/initial_review/enrique/vllm__MODEL [more run dirs ...] \
        --out data/processed/variations/initial_review/review_enrique

Reviewer columns are left empty (fill with y / n / ? and a note). The summary shows what to check before trusting a run:
failures, unchanged texts, new value missing from the text, verification pass rate (only when the run used --verify).
"""
import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REVIEW_COLS = ["new_value_expressed", "old_value_gone", "other_params_preserved", "natural_and_same_format",
               "replacement_value_sensible", "reviewer_notes", "reviewer"]
INFO_COLS = ["variant_id", "dataset", "domain", "changed_parameter", "original_value", "new_value", "generation_method",
             "verification_passed", "verification_issues", "original_text", "new_text"]


def read(path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()] if path.exists() else []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dirs", nargs="+", type=Path)
    ap.add_argument("--out", type=Path, help="output path without extension (default: <first run dir>/review_sheet)")
    args = ap.parse_args()
    ok, failed = [], []
    for d in args.run_dirs:
        if not (d / "variations.jsonl").exists() and not (d / "failures.jsonl").exists():
            sys.exit(f"error: {d} has no variations.jsonl / failures.jsonl (pass the <engine>__<model> run directory)")
        ok += [r for r in read(d / "variations.jsonl") if r.get("status") == "ok"]
        failed += read(d / "failures.jsonl")
    ok.sort(key=lambda r: (r["dataset"], r["domain"], r["source_record_id"], r["changed_parameter"]))
    out = args.out or args.run_dirs[0] / "review_sheet"
    out.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for r in ok:
        v = r.get("verification") or {}
        rows.append({**r, "verification_passed": v.get("passed", ""), "verification_issues": v.get("issues", "") or v.get("error", ""),
                     **{c: "" for c in REVIEW_COLS}})
    with out.with_suffix(".csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=INFO_COLS + REVIEW_COLS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    with out.with_suffix(".md").open("w", encoding="utf-8") as f:
        f.write(f"# Variation review sheet ({len(rows)} variants)\n\nFor each variant judge: new value expressed? old value gone? other four parameters preserved? "
                "natural text in the original format? replacement value sensible for the domain? Record it in the CSV.\n")
        for r in ok:
            v = r.get("verification") or {}
            f.write(f"\n---\n\n### `{r['variant_id']}`\n\n- dataset **{r['dataset']}** · domain **{r['domain']}** · changed **{r['changed_parameter']}** · "
                    f"method {r['generation_method']}" + (f" · verifier: {'pass' if v.get('passed') else 'FAIL'}" if v and 'passed' in v else "") + "\n"
                    f"- **old:** {r['original_value']}\n- **new:** {r['new_value']}\n")
            if v.get("issues"):
                f.write(f"- verifier issues: {v['issues']}\n")
            f.write(f"\n**Original**\n\n```text\n{r['original_text']}\n```\n\n**New**\n\n```text\n{r['new_text']}\n```\n")

    # ---- readiness summary
    print(f"run dirs: {', '.join(map(str, args.run_dirs))}")
    print(f"ok: {len(ok)}   failed: {len(failed)}")
    for fr in failed[:5]:
        print(f"  FAILED {fr.get('variant_id')}: {fr.get('stage')}: {(fr.get('error') or '')[:150]}")
    llm = [r for r in ok if r["generation_method"] == "llm"]
    print(f"generated by LLM: {len(llm)}   by direct substitution (structured seeds, no LLM): {len(ok) - len(llm)}")
    unchanged = [r["variant_id"] for r in llm if r["new_text"].strip() == r["original_text"].strip()]
    # soft check: a long replacement value is usually paraphrased, so only warn for short ones
    missing = [r["variant_id"] for r in llm if len(r["new_value"]) <= 40 and r["new_value"].lower() not in r["new_text"].lower()]
    print(f"identical to original: {len(unchanged)}   short new value not found verbatim in text (check by eye, paraphrase is allowed): {len(missing)}")
    ver = [r["verification"] for r in ok if r.get("verification") and "passed" in r["verification"]]
    if ver:
        print(f"verifier passed: {sum(v['passed'] for v in ver)}/{len(ver)}")
    else:
        print("verifier: not used in this run (add --verify to `vary` for a second-model check)")
    per = defaultdict(Counter)
    for r in ok:
        per[r["dataset"]][r["domain"]] += 1
    for ds in sorted(per):
        print(f"  {ds}: " + ", ".join(f"{d} {n}" for d, n in sorted(per[ds].items())))
    print(f"wrote {out.with_suffix('.csv')} and {out.with_suffix('.md')}")
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
